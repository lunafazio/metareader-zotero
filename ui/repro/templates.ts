import type { AnalysisPlan, PlanStep, ResultsSchema } from "./schemas";

export type TemplateId = "r" | "targets" | "python" | "snakemake";

export const TEMPLATES: Record<TemplateId, { label: string; script: string; command: string; lang: "R" | "Python" }> = {
  r: { label: "Monolithic R script", script: "analysis.R", command: "Rscript analysis.R", lang: "R" },
  targets: { label: "R targets pipeline", script: "_targets.R", command: `Rscript -e 'targets::tar_make()'`, lang: "R" },
  python: { label: "Monolithic Python script", script: "analysis.py", command: "python3 analysis.py", lang: "Python" },
  snakemake: { label: "Python Snakemake pipeline", script: "Snakefile", command: "snakemake --cores 1", lang: "Python" },
};

export const TODO_MARK = "TODO(LLM)";

function wrap(text: string, width = 92): string[] {
  const words = text.replace(/\s+/g, " ").trim().split(" ");
  const lines: string[] = [];
  let cur = "";
  for (const w of words) {
    if (cur && (cur + " " + w).length > width) {
      lines.push(cur);
      cur = w;
    } else cur = cur ? cur + " " + w : w;
  }
  if (cur) lines.push(cur);
  return lines;
}

/** Comment header describing a step; identical across templates apart from indentation. */
function stepHeader(s: PlanStep, indent = ""): string {
  const c = indent + "# ";
  const short = s.summary.split("\n")[0];
  const long = short.length > 80 || s.summary.includes("\n");
  const out = [`${c}==== ${s.id} [${s.kind}]: ${long ? short.slice(0, 77) + "…" : short} ====`];
  if (long) {
    out.push(`${c}Summary:`);
    out.push(...wrap(s.summary).map((l) => `${c}  ${l}`));
  }
  if (s.quote) {
    out.push(`${c}Source quote:`);
    out.push(...wrap(`"${s.quote}"`).map((l) => `${c}  ${l}`));
  }
  if (s.inputs.length) out.push(`${c}Inputs: ${s.inputs.join(", ")}`);
  out.push(`${c}Depends on: ${s.depends_on.join(", ") || "—"}`);
  if (s.produces.length) out.push(`${c}Produces: ${s.produces.join(", ")}`);
  return out.join("\n");
}

const target = (s: PlanStep) => s.id.toLowerCase();
const doneFile = (s: PlanStep) => `outputs/.steps/${s.id}.done`;

export function masterScript(t: TemplateId, plan: AnalysisPlan, schema: ResultsSchema | undefined, title: string): string {
  const head = [
    `# Reproduction of: ${title}`,
    `# DOI: ${schema?.paper.doi ?? ""}`,
    `# Generated by MetaReader. Every ${TODO_MARK} block must be implemented; remove the marker when done.`,
    `# Targets: results_schema.json · Plan: analysis_plan.json · Output: outputs/results.json`,
    `# (format: schemas/results_output.schema.json)`,
    "",
  ].join("\n");
  const steps = plan.steps;

  if (t === "r" || t === "python") {
    const body = steps
      .map((s) => `${stepHeader(s)}\n# ${TODO_MARK}: implement ${s.id}${s.kind === "results" ? " — write outputs/results.json" : ""}\n`)
      .join("\n");
    const prelude = t === "r" ? `# ${TODO_MARK}: load required packages\n` : `# ${TODO_MARK}: imports\n`;
    return head + prelude + "\n" + body;
  }

  if (t === "targets") {
    const tars = steps
      .map((s) => {
        const deps = s.depends_on.map((d) => d.toLowerCase());
        const fmt = s.kind === "results" ? `, format = "file"` : "";
        const ret = s.kind === "results" ? `"outputs/results.json"` : "NULL";
        return `${stepHeader(s, "  ")}\n  tar_target(${target(s)}, {\n    ${deps.length ? `# uses: ${deps.join(", ")}\n    ` : ""}# ${TODO_MARK}: implement ${s.id}\n    ${ret}\n  }${fmt})`;
      })
      .join(",\n\n");
    return `${head}library(targets)\n# ${TODO_MARK}: declare packages\ntar_option_set(packages = c())\n\nlist(\n${tars}\n)\n`;
  }

  // snakemake
  const byId = new Map(steps.map((s) => [s.id, s]));
  const rules = steps
    .map((s) => {
      const inputs = [...s.inputs, ...s.depends_on.map((d) => (byId.get(d)?.kind === "results" ? "outputs/results.json" : doneFile(byId.get(d) ?? s)))];
      const out = s.kind === "results" ? `"outputs/results.json"` : `touch("${doneFile(s)}")`;
      return `${stepHeader(s)}\nrule ${target(s)}:\n    input: ${inputs.length ? inputs.map((i) => `"${i}"`).join(", ") : "[]"}\n    output: ${out}\n    run:\n        # ${TODO_MARK}: implement ${s.id}\n        pass\n`;
    })
    .join("\n");
  return `${head}rule all:\n    input: "outputs/results.json"\n\n${rules}`;
}

export function agentPrompt(t: TemplateId, opts: { folder: string; hasCode: boolean; dataFiles: string[] }): string {
  const tpl = TEMPLATES[t];
  const specific: Record<TemplateId, string> = {
    r: `Implement each step section of analysis.R in place, in order.`,
    python: `Implement each step section of analysis.py in place, in order.`,
    targets: `Implement each tar_target() in _targets.R. Pass data between targets as target values. The final target must write outputs/results.json and return its path (format = "file"). Helper functions may go in R/.`,
    snakemake: `Implement the run: block of each rule in the Snakefile (you may move code into scripts/ and use script: instead). Intermediate data goes in outputs/intermediate/. The final rule must write outputs/results.json.`,
  };
  return `You are working in a computational reproduction package at:
${opts.folder}

Goal: implement the analysis so that running \`${tpl.command}\` from the package root reproduces the paper's results.

Read first:
- ${tpl.script} — master ${tpl.lang} script with one section per analysis step. Each section has the step summary and the verbatim quote from the paper it implements.
- analysis_plan.json — the same steps as structured data (ids, inputs, dependencies, result ids each step produces).
- results_schema.json — the reproduction targets (ids, descriptions, quotes, expected values).
- schemas/results_output.schema.json — the required format of outputs/results.json.
- data/ — input data (${opts.dataFiles.length ? opts.dataFiles.join(", ") : "none uploaded"}). Never modify these files.${opts.hasCode ? "\n- code/ — the original authors' code. Prefer reusing their logic; cite the file you took it from in a comment." : ""}

Rules:
1. ${specific[t]}
2. Replace every \`${TODO_MARK}\` marker with working code and delete the marker. Keep the step header comments (ids, summaries, quotes) intact and in order.
3. Use paths relative to the package root.
4. Compute every result from the data. NEVER copy expected values from results_schema.json into the output; the point is to test whether they reproduce.
5. outputs/results.json: {"results": [{"id": "<result id>", "value": <unrounded number or string>, "step": "<step id>"}, ...]}. Use "table" (array of rows, same layout as expected, header row included) for table results, and "file" for figure results (save figures as outputs/figures/<result id>.png). If a result cannot be computed, emit it with "value": null and a "note" explaining why.
6. List required packages in ${tpl.lang === "R" ? "install.R (install.packages(...) calls)" : "requirements.txt"}.
7. If something in the paper is ambiguous, pick the most plausible reading and document it in a comment starting with "# ASSUMPTION:".
8. When finished, run the pipeline once if you can and fix errors.
`;
}

export function packageReadme(t: TemplateId, title: string, doi: string): string {
  const tpl = TEMPLATES[t];
  return `# Reproduction package: ${title}

DOI: ${doi}

| Path | Contents |
|---|---|
| \`${tpl.script}\` | Master ${tpl.lang} ${t === "targets" || t === "snakemake" ? "pipeline" : "script"} (${tpl.label}) |
| \`analysis_plan.json\` | Analysis steps with verbatim source quotes |
| \`results_schema.json\` | Reproduction targets with expected values |
| \`schemas/\` | JSON Schemas for the files above and for outputs/results.json |
| \`data/\` | Input data |
| \`code/\` | Original code provided by the authors (if any) |
| \`targets/figures/\` | Crops of the original figures |
| \`outputs/\` | Reproduced results (\`results.json\`), figures, run log |
| \`report.html\` | Reproduction report |
| \`AGENT_PROMPT.md\` | Instructions used for LLM code generation |

Run: \`${tpl.command}\`
`;
}

// The "MetaReader Package": one stored attachment per parent item whose storage folder holds every file
// MetaReader generates. The attachment's main file is an HTML overview of the folder; because it is text/*,
// Zotero file sync uploads the whole folder as a zip. Zotero doesn't allow children under attachments, so the
// folder contents are shown in the item pane section (itempane.ts) instead of as a deeper tree level.

export const PACKAGE_FILE = "metareader-package.html";
export const PACKAGE_TITLE = "MetaReader Package";

export interface Entry {
  path: string; // relative to the package folder, "/"-separated
  size: number;
  modified: number;
  sha256: string | null;
}

export function isPackage(item: any): boolean {
  return !!item?.isAttachment?.() && item.isImportedAttachment() && item.attachmentFilename === PACKAGE_FILE;
}

export function getPackage(parent: any): any | undefined {
  if (!parent?.isRegularItem?.()) return undefined;
  for (const id of parent.getAttachments()) {
    const att = Zotero.Items.get(id);
    if (isPackage(att)) return att;
  }
  return undefined;
}

export async function ensurePackage(parent: any): Promise<any> {
  const existing = getPackage(parent);
  if (existing) return existing;
  const tmpDir = PathUtils.join(PathUtils.tempDir, `metareader-${Zotero.Utilities.randomString()}`);
  await IOUtils.makeDirectory(tmpDir, { createAncestors: true });
  const tmp = PathUtils.join(tmpDir, PACKAGE_FILE);
  await IOUtils.writeUTF8(tmp, overviewHtml(parent, []));
  try {
    return await Zotero.Attachments.importFromFile({
      file: tmp,
      parentItemID: parent.id,
      title: PACKAGE_TITLE,
      contentType: "text/html",
      charset: "utf-8",
    });
  } finally {
    await IOUtils.remove(tmpDir, { recursive: true, ignoreAbsent: true });
  }
}

export const packageDir = (pkg: any): string => Zotero.Attachments.getStorageDirectory(pkg).path;

async function sha256(p: string): Promise<string> {
  const digest = await crypto.subtle.digest("SHA-256", await IOUtils.read(p));
  return Array.from(new Uint8Array(digest), (b) => b.toString(16).padStart(2, "0")).join("");
}

/** Files of the package (or a subfolder), skipping the overview, hidden files and tool caches. */
export async function listPackage(root: string, hash = false, sub = ""): Promise<Entry[]> {
  const out: Entry[] = [];
  const walk = async (dir: string) => {
    if (!(await IOUtils.exists(dir))) return;
    for (const p of await IOUtils.getChildren(dir)) {
      const name = PathUtils.filename(p);
      if (name.startsWith(".") || name === "__pycache__" || name === "_targets") continue;
      const st = await IOUtils.stat(p);
      if (st.type === "directory") await walk(p);
      else if (!(dir === root && name === PACKAGE_FILE)) {
        out.push({
          path: p.slice(root.length + 1),
          size: st.size,
          modified: st.lastModified ?? 0,
          sha256: hash && st.size < 500_000_000 ? await sha256(p) : null,
        });
      }
    }
  };
  await walk(sub ? PathUtils.join(root, ...sub.split("/")) : root);
  return out.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
}

const esc = (s: string) => s.replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]!);

export const formatSize = (n: number) =>
  n < 1024 ? `${n} B` : n < 1024 ** 2 ? `${(n / 1024).toFixed(0)} KB` : `${(n / 1024 ** 2).toFixed(1)} MB`;

function overviewHtml(parent: any, files: Entry[]): string {
  const title = parent.getDisplayTitle();
  const doi = parent.getField?.("DOI") || "";
  const rows = files.map((f) => `<tr><td>${esc(f.path)}</td><td>${formatSize(f.size)}</td><td>${new Date(f.modified).toISOString().slice(0, 16).replace("T", " ")}</td></tr>`).join("");
  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>${esc(PACKAGE_TITLE)}: ${esc(title)}</title>
<style>body{font:14px system-ui,sans-serif;margin:2em;max-width:60em}td,th{text-align:left;padding:2px 12px 2px 0}td+td{white-space:nowrap}</style>
</head><body>
<h1>${esc(PACKAGE_TITLE)}</h1>
<p><b>${esc(title)}</b>${doi ? ` · doi:${esc(doi)}` : ""}</p>
<p>Files generated by the MetaReader Zotero plugin (structured full text, reproduction package). Open them in Zotero with right-click → Open in MetaReader.</p>
<table><tr><th>File</th><th>Size</th><th>Modified (UTC)</th></tr>${rows}</table>
</body></html>
`;
}

type Listener = (parent: any, pkg: any) => void;
const listeners = new Set<Listener>();
/** Get notified after a package's contents changed (used by the item pane section). */
export function onPackageChanged(fn: Listener): () => void {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

/** Rewrite the overview (which also marks the attachment as changed for file sync) and refresh views. */
export async function updateOverview(parent: any, pkg: any) {
  const dir = packageDir(pkg);
  await IOUtils.writeUTF8(PathUtils.join(dir, PACKAGE_FILE), overviewHtml(parent, await listPackage(dir)));
  Zotero.Notifier.trigger("refresh", "item", [pkg.id]);
  for (const fn of listeners) fn(parent, pkg);
}
